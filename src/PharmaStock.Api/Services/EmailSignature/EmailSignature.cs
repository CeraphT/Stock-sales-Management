using System.Net;
using System.Reflection;
using System.Text.RegularExpressions;

namespace PharmaStock.Api.Services;

/// <summary>Which mfSPACE footer an outgoing email gets.</summary>
public enum EmailSignatureKind
{
    /// <summary>Email sent in mfSPACE's own name (password reset, reports, reminders,
    /// support): full signature (mfSPACE, no personal names: phones, address, GDPR line).</summary>
    Company,
    /// <summary>Email a customer sends to THEIR contact through the app (landlord to
    /// tenant): neutral "sent via the app" footer, no mfSPACE personal details, and
    /// replies go to the sender.</summary>
    Relay,
}

/// <summary>Appends the mfSPACE signature to every outgoing email (called once, from
/// <see cref="EmailService.SendAsync"/>, so no template can skip it) and builds the
/// plain-text part. The signature files are generated by the mfspace-signature kit
/// (D:\Claude Coding\mfspace-signature, <c>node build.mjs</c>) and embedded here;
/// copy the new dist/signature-{app,relay}.{fr,en}.{html,txt} after changing it.</summary>
public static class EmailSignature
{
    public const string Marker = "<!-- mfspace-signature -->";

    public static string Lang(string? lang) => string.Equals(lang, "en", StringComparison.OrdinalIgnoreCase) ? "en" : "fr";

    public static (string Html, string Text) Apply(string? htmlBody, string appName, EmailSignatureKind kind, string? lang)
    {
        var body = htmlBody ?? "";
        var l = Lang(lang);
        var file = kind == EmailSignatureKind.Relay ? "relay" : "app";
        var sigHtml = Load($"signature-{file}.{l}.html").Replace("{{APP_NAME}}", appName);
        var sigText = Load($"signature-{file}.{l}.txt").Replace("{{APP_NAME}}", appName);

        if (body.Contains(Marker)) return (body, ToText(body));
        var block = $"{Marker}<br><br>{sigHtml}";
        var close = body.LastIndexOf("</body>", StringComparison.OrdinalIgnoreCase);
        var html = close >= 0 ? body.Insert(close, block) : body + block;
        var text = ToText(body).TrimEnd() + "\n\n-- \n" + sigText;
        return (html, text);
    }

    private static readonly Dictionary<string, string> Cache = new();

    private static string Load(string name)
    {
        lock (Cache)
        {
            if (Cache.TryGetValue(name, out var s)) return s;
            using var stream = Assembly.GetExecutingAssembly().GetManifestResourceStream("EmailSignature." + name)
                ?? throw new InvalidOperationException($"Missing embedded email signature {name}.");
            using var reader = new StreamReader(stream);
            return Cache[name] = reader.ReadToEnd();
        }
    }

    /// <summary>Rough HTML to plain text for the text/plain alternative.</summary>
    public static string ToText(string html)
    {
        var s = Regex.Replace(html, @"<(script|style|head)[\s\S]*?</\1>", "", RegexOptions.IgnoreCase);
        s = Regex.Replace(s, @"<a\s[^>]*href=""(https?://[^""]+)""[^>]*>([\s\S]*?)</a>", m =>
            m.Groups[2].Value.Contains(m.Groups[1].Value) ? m.Groups[2].Value : $"{m.Groups[2].Value} ({m.Groups[1].Value})", RegexOptions.IgnoreCase);
        s = Regex.Replace(s, @"<br\s*/?>", "\n", RegexOptions.IgnoreCase);
        s = Regex.Replace(s, @"</(p|div|tr|h[1-6]|li|table)>", "\n", RegexOptions.IgnoreCase);
        s = Regex.Replace(s, @"<li[^>]*>", "- ", RegexOptions.IgnoreCase);
        s = Regex.Replace(s, @"<[^>]+>", "");
        s = WebUtility.HtmlDecode(s).Replace('\u00A0', ' ');
        s = Regex.Replace(s, @"[ \t]+\n", "\n");
        s = Regex.Replace(s, @"\n{3,}", "\n\n");
        return s.Trim();
    }
}
