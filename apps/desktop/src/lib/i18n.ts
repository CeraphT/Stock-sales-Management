/** Reactive translator hook. `t(en)` returns the French string when the app
 * language is "fr", else the English source. */
export function useT(): (en: string) => string {
  const language = useLanguageStore((s) => s.language);
  return (en: string) => (language === "fr" ? FR[en] ?? en : en);
}
